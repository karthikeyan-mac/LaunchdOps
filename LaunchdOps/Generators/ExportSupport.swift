import CryptoKit
import Foundation

struct ExportFile: Hashable, Sendable {
  var path: String
  var contents: Data
  var mode: Int
}

struct FileTree: Sendable {
  private(set) var files: [ExportFile] = []

  mutating func add(_ path: String, _ contents: Data, mode: Int = 0o644) {
    files.removeAll { $0.path == path }
    files.append(ExportFile(path: path, contents: contents, mode: mode))
  }

  mutating func add(_ path: String, text: String, mode: Int = 0o644) {
    add(path, Data(text.utf8), mode: mode)
  }

  func fileWrapper() -> FileWrapper {
    let root = FileWrapper(directoryWithFileWrappers: [:])
    for file in files.sorted(by: { $0.path < $1.path }) {
      var components = file.path.split(separator: "/").map(String.init)
      guard let name = components.popLast() else { continue }
      var directory = root
      for component in components {
        if let existing = directory.fileWrappers?[component], existing.isDirectory {
          directory = existing
        } else {
          let child = FileWrapper(directoryWithFileWrappers: [:])
          child.preferredFilename = component
          directory.addFileWrapper(child)
          directory = child
        }
      }
      let wrapper = FileWrapper(regularFileWithContents: file.contents)
      wrapper.preferredFilename = name
      wrapper.fileAttributes[FileAttributeKey.posixPermissions.rawValue] = NSNumber(value: file.mode)
      directory.addFileWrapper(wrapper)
    }
    return root
  }
}

enum Shell {
  static func quoted(_ value: String) -> String {
    "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
  }
}

enum Hashing {
  static func sha256(_ data: Data) -> String {
    SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
  }
}

enum GeneratorInfo {
  static var version: String {
    Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "1.0"
  }

  static var banner: String {
    "Generated by LaunchdOps \(version)"
  }
}

struct OutlineLine: Identifiable, Hashable, Sendable {
  let path: String
  let name: String
  let depth: Int
  let isFolder: Bool

  var id: String { path }
}

enum OutputOutline {
  static func lines(for paths: [String], root: String) -> [OutlineLine] {
    var result = [OutlineLine(path: "", name: "\(root)/", depth: 0, isFolder: true)]
    var seen = Set<String>()
    for path in paths.sorted() {
      let parts = path.split(separator: "/").map(String.init)
      for index in parts.indices {
        let prefix = parts[...index].joined(separator: "/")
        guard seen.insert(prefix).inserted else { continue }
        let isFolder = index < parts.count - 1
        result.append(OutlineLine(
          path: prefix,
          name: isFolder ? "\(parts[index])/" : parts[index],
          depth: index + 1,
          isFolder: isFolder
        ))
      }
    }
    return result
  }
}
